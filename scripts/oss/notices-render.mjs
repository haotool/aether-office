const fence = (text) => {
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((s) => s.length));
  const ticks = '`'.repeat(longest + 1);
  return `${ticks}text\n${normalizeText(text)}\n${ticks}`;
};
const cell = (s) =>
  String(s ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');
