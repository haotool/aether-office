// Text output: the console table, the `--target` blocker list and the generated docs/quality/scorecard.md.
import { formatQualityInputs } from './inputs.mjs';
import { blockers } from './model.mjs';

const fmtScore = (score) => (score === null ? 'n/a' : score.toFixed(1));
const fmtValue = (r) =>
  r.value === null
    ? '-'
    : `${r.value}${r.unit && r.unit !== '%' ? ` ${r.unit}` : ''}${r.unit === '%' ? '%' : ''}`;
const limitText = (r) =>
  r.limit === null ? '-' : `${r.minimum ? '>= ' : ''}${r.limit}${r.unit === '%' ? '%' : ''}`;
const escapeCell = (text) => String(text).replaceAll('|', '\\|');

/** "label x12 (-3.4)" for the largest penalties of an area. */
export function topPenalties(area, count = 5) {
  return blockers(area)
    .slice(0, count)
    .map((r) => `${r.id} ${r.value}${r.unit === '%' ? '%' : ''} (-${r.penalty})`);
}

export function renderTable(report, floors, { target, details = 5, brief = false } = {}) {
  const rows = report.areas.map((a) => [
    a.name,
    fmtScore(a.score),
    floors.floors[a.name] === undefined ? '-' : fmtScore(floors.floors[a.name]),
    `${a.measured}%`,
    topPenalties(a).join(', ') || 'none',
  ]);
  const head = ['area', 'score', 'floor', 'measured', 'top penalties'];
  const widths = head.map((h, i) => Math.max(h.length, ...rows.map((r) => r[i].length)));
  const line = (cells) =>
    cells
      .map((c, i) => c.padEnd(widths[i]))
      .join('  ')
      .trimEnd();
  const out = [line(head), line(widths.map((w) => '-'.repeat(w))), ...rows.map(line)];
  if (report.inputs) out.push('', `inputs: ${formatQualityInputs(report.inputs)}`);
  out.push('', `overall ${fmtScore(report.overall)}`);
  const goal = target ?? floors.target;
  const shown = brief ? [] : report.areas.filter((a) => a.score !== null && a.score < goal);
  for (const area of shown) {
    out.push('', `${area.name}: ${fmtScore(area.score)}${` -> ${goal}`}`);
    for (const r of blockers(area)) {
      out.push(`  -${r.penalty}  ${r.id}: ${r.label} = ${fmtValue(r)} (limit ${limitText(r)})`);
      for (const d of r.details.slice(0, details)) out.push(`        ${d}`);
      if (r.details.length > details)
        out.push(`        ... ${r.details.length - details} more (--json lists up to 40)`);
    }
  }
  const notRun = report.areas.flatMap((a) =>
    a.rules.filter((r) => r.status === 'skipped').map((r) => `${a.name}/${r.id}: ${r.note}`),
  );
  if (notRun.length)
    out.push('', 'not measured (excluded from the score):', ...notRun.map((n) => `  ${n}`));
  return out.join('\n');
}

function ruleTable(area) {
  const rows = area.rules.map((r) => {
    const state =
      r.status === 'skipped'
        ? 'not run'
        : r.status === 'info'
          ? 'info'
          : r.penalty > 0
            ? 'fail'
            : 'pass';
    return `| ${escapeCell(r.label)}${r.note ? ` (${escapeCell(r.note)})` : ''} | \`${r.id}\` | ${fmtValue(r)} | ${limitText(r)} | ${r.weight || '-'} | ${r.penalty ? `-${r.penalty}` : '0'} | ${state} |`;
  });
  return [
    '| Rule | Id | Value | Limit | Weight | Penalty | State |',
    '| --- | --- | ---: | ---: | ---: | ---: | --- |',
    ...rows,
  ].join('\n');
}

function findings(area, limit = 8) {
  return blockers(area).map((r) => {
    const lines = r.details.slice(0, limit).map((d) => `  ${d}`);
    if (r.details.length > limit)
      lines.push(`  ... ${r.details.length - limit} more in scorecard.json`);
    return `**${r.id}** (-${r.penalty}): ${r.label}\n\n\`\`\`text\n${lines.join('\n')}\n\`\`\``;
  });
}

export function renderMarkdown(report, floors) {
  const summary = report.areas.map(
    (a) =>
      `| ${a.title} (\`${a.name}\`) | ${fmtScore(a.score)} | ${floors.floors[a.name] === undefined ? '-' : fmtScore(floors.floors[a.name])} | ${a.measured}% | ${escapeCell(topPenalties(a, 3).join(', ') || 'none')} |`,
  );
  const sections = report.areas.map((a) => {
    const info = a.rules.filter((r) => r.status === 'info' && r.details.length);
    const infoText = info.map(
      (r) => `${r.label}: ${r.value}\n\n\`\`\`text\n${r.details.slice(0, 12).join('\n')}\n\`\`\``,
    );
    const failing = findings(a);
    return [
      `## ${a.title}`,
      '',
      `Score ${fmtScore(a.score)}, floor ${floors.floors[a.name] === undefined ? '-' : fmtScore(floors.floors[a.name])}, ${a.measured}% of the rule weight measured.`,
      '',
      ruleTable(a),
      ...(failing.length
        ? ['', '### What costs points', '', ...failing.flatMap((f) => [f, ''])]
        : ['']),
      ...infoText.flatMap((t) => [t, '']),
    ].join('\n');
  });
  return (
    [
      '# Quality scorecard',
      '',
      'Generated by `pnpm run quality:report` from `scripts/quality`; do not edit. The rules, weights and how to challenge them are in [README.md](README.md). `pnpm run quality:check` fails when this file is stale or an area is below its floor in [floors.json](floors.json).',
      '',
      `Overall: **${fmtScore(report.overall)}** (mean of the scored areas; target ${floors.target}).`,
      '',
      '| Area | Score | Floor | Measured | Largest penalties |',
      '| --- | ---: | ---: | ---: | --- |',
      ...summary,
      '',
      'A score is 100 minus the penalties of the rules that could be measured. A rule that needs something absent (a build, a browser run, a GPU, a binary) is "not run": it costs nothing and its area reports how much of its weight was measured. An area with under half its weight measured is n/a.',
      '',
      ...sections.flatMap((s) => [s, '']),
    ]
      .join('\n')
      .replace(/\n{3,}/g, '\n\n')
      .trimEnd() + '\n'
  );
}
